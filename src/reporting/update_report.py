"""Regenerate the measured sections of the Milestone 1 report.

Every number in the report that comes from an experiment lives between a pair
of markers:

    <!-- AUTO:transfer_study -->
    ...generated...
    <!-- /AUTO:transfer_study -->

This module rewrites what is between each pair from the artifacts under
``outputs/``. Prose outside the markers is never touched. A section whose
artifacts do not exist yet is filled with a visible "not run yet" notice rather
than an invented number, so an unfinished report is obvious instead of wrong.

    python -m src.reporting.update_report
    python -m src.reporting.update_report --check    # exit 1 if anything is stale

Run it after any experiment finishes, then regenerate the PDF.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Callable

REPORT = Path("outputs/final_submission/milestone_1_report.md")

PENDING = ("> **Not run yet.** This section is generated by "
           "`python -m src.reporting.update_report` from `{source}`. "
           "Produce it with `{command}`, then rerun the updater.")


def _read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def _percent(value: float) -> str:
    return f"{value * 100:.2f}%"


# ---------------------------------------------------------------------------
# Section builders. Each returns the markdown that goes between its markers.
# ---------------------------------------------------------------------------
def build_transfer_study() -> str:
    rows = _read_json(Path("outputs/transfer_study/study_results.json"))
    if not rows:
        return PENDING.format(
            source="outputs/transfer_study/study_results.json",
            command="python -m src.training.transfer_study --config configs/p5_transfer_study.yaml")

    rows = sorted(rows, key=lambda r: -r["best_val_macro_f1"])
    lines = [
        "The random search in section 7 varied four factors at once and only ever "
        "fine-tuned at learning rates of 1e-3 and 3e-3. This controlled study changes "
        "one factor at a time, holding split, seed, image size, augmentation, batch "
        "size, epoch limit, optimizer and weight decay constant "
        "(`configs/p5_transfer_study.yaml`). All values are validation metrics on the "
        "duplicate-safe `stratified_group_v2` split.",
        "",
        "| Run | Architecture | Backbone | Learning rate | Best epoch | Val accuracy | Val macro F1 | Val loss |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            f"| {row['label']} | {row['model_name']} | "
            f"{'frozen' if row['freeze_backbone'] else 'fine-tuned'} | "
            f"{row['learning_rate']:g} | {row['best_epoch']} | "
            f"{_percent(row['best_val_accuracy'])} | {_percent(row['best_val_macro_f1'])} | "
            f"{row['best_val_loss']:.4f} |")

    frozen = [r for r in rows if r["freeze_backbone"]]
    tuned = [r for r in rows if not r["freeze_backbone"]]
    lines.append("")
    if frozen and tuned:
        best_frozen = max(frozen, key=lambda r: r["best_val_macro_f1"])
        best_tuned = max(tuned, key=lambda r: r["best_val_macro_f1"])
        delta = (best_tuned["best_val_macro_f1"] - best_frozen["best_val_macro_f1"]) * 100
        verb = "outperforms" if delta >= 0 else "underperforms"
        lines.append(
            f"Fine-tuning at an appropriate learning rate {verb} the frozen backbone by "
            f"{abs(delta):.2f} macro-F1 points ({best_tuned['label']} at "
            f"{_percent(best_tuned['best_val_macro_f1'])} against {best_frozen['label']} at "
            f"{_percent(best_frozen['best_val_macro_f1'])}). In the original random search "
            "every fine-tuned trial scored between 1.92% and 5.76% accuracy; the cause was the "
            "learning rate, not fine-tuning itself. See section 12.1.")
    architectures = sorted({r["model_name"] for r in rows})
    if len(architectures) > 1:
        parts = []
        for name in architectures:
            top = max((r for r in rows if r["model_name"] == name), key=lambda r: r["best_val_macro_f1"])
            parts.append(f"{name} peaks at {_percent(top['best_val_macro_f1'])} macro F1 ({top['label']})")
        lines += ["", "Across the two pretrained architectures: " + "; ".join(parts) + "."]
    lines += ["", "![Transfer study](../transfer_study/figures/transfer_study.png)"]
    return "\n".join(lines)


def build_p4_architectures() -> str:
    selection = _read_json(Path("outputs/p4_scoped/search/p4_architectures_selection.json"))
    if not selection:
        return PENDING.format(
            source="outputs/p4_scoped/search/p4_architectures_selection.json",
            command="python -m src.training.p4_experiments architectures --config configs/p4_architecture.yaml")

    results = sorted(selection["results"], key=lambda r: -r["best_val_macro_f1"])
    lines = [
        "Three from-scratch architectures were compared on identical data, seed, "
        "augmentation, learning rate, weight decay and epoch budget "
        "(`configs/p4_architecture.yaml`): the baseline `SimpleCNN`, a delayed-pooling "
        "CNN that keeps spatial resolution for longer, and a residual CNN with "
        "projection shortcuts. Selection is by validation macro F1.",
        "",
        "| Architecture | Parameters | Best epoch | Val accuracy | Val macro F1 | Val loss | Train time (s) |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in results:
        lines.append(
            f"| {row['model']['name']} | {row['parameter_count']:,} | {row['best_epoch']} | "
            f"{_percent(row['best_val_accuracy'])} | {_percent(row['best_val_macro_f1'])} | "
            f"{row['best_val_loss']:.4f} | {row['training_seconds']:.0f} |")

    winner = selection["best_trial"]
    baseline = next((r for r in results if r["model"]["name"] == "simple_cnn"), None)
    lines.append("")
    sentence = (f"The strongest scratch architecture is **{winner['model']['name']}** at "
                f"{_percent(winner['best_val_macro_f1'])} validation macro F1.")
    if baseline and baseline is not winner:
        gain = (winner["best_val_macro_f1"] - baseline["best_val_macro_f1"]) * 100
        sentence += (f" That is {gain:+.2f} macro-F1 points against the `SimpleCNN` baseline, whose "
                     f"single 256-channel bottleneck before global average pooling leaves only 256 "
                     f"features to separate 200 classes.")
    lines.append(sentence)
    return "\n".join(lines)


def build_eval_geometry() -> str:
    squash = _read_json(Path("outputs/evaluation/p5_corrected/metrics.json"))
    crop = _read_json(Path("outputs/evaluation/p5_corrected_center_crop/metrics.json"))
    if not crop or not squash:
        return PENDING.format(
            source="outputs/evaluation/p5_corrected_center_crop/metrics.json",
            command="scripts/run_milestone1_completion.ps1 -Stage eval")

    lines = [
        "Training crops with `RandomResizedCrop`, which preserves aspect ratio; the "
        "committed evaluation pipeline used `Resize((224, 224))`, which squashes a "
        "500x375 photo into a square. The same checkpoint was therefore evaluated twice "
        "on the same untouched test split, changing only the resize geometry. No weights "
        "were retrained.",
        "",
        "| Evaluation geometry | Accuracy | Macro precision | Macro recall | Macro F1 | Test loss |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, metrics in (("`squash` - Resize((224,224)), as committed", squash),
                          ("`center_crop` - Resize(256) + CenterCrop(224)", crop)):
        lines.append(
            f"| {name} | {_percent(metrics['accuracy'])} | {_percent(metrics['macro_precision'])} | "
            f"{_percent(metrics['macro_recall'])} | {_percent(metrics['macro_f1'])} | "
            f"{metrics['test_loss']:.5f} |")

    delta = (crop["accuracy"] - squash["accuracy"]) * 100
    lines += ["", f"Preserving aspect ratio at evaluation time changes test accuracy by "
                  f"{delta:+.2f} points at zero training cost, which isolates the "
                  f"train/evaluation preprocessing mismatch as a measurable effect rather "
                  f"than an assumption."]
    return "\n".join(lines)


def build_final_results() -> str:
    sources = [
        ("P4 Scratch CNN (legacy split)", "outputs/evaluation/p4/metrics.json"),
        ("P5 ResNet18 Transfer (legacy split)", "outputs/evaluation/p5/metrics.json"),
        ("P5 ResNet18 Transfer (corrected split)", "outputs/evaluation/p5_corrected/metrics.json"),
        ("P5 transfer-study winner (corrected split)", "outputs/evaluation/p5_study_winner/metrics.json"),
        ("P4 best scratch architecture (corrected split)", "outputs/evaluation/p4_study_winner/metrics.json"),
    ]
    lines = [
        "All figures below are measured on the untouched 5,794-image "
        "`Multimodal-Fatima/CUB_test:test` split, used only after model selection.",
        "",
        "| Model | Test loss | Accuracy | Macro precision | Macro recall | Macro F1 |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    found = 0
    for label, path in sources:
        metrics = _read_json(Path(path))
        if not metrics:
            continue
        found += 1
        lines.append(
            f"| {label} | {metrics['test_loss']:.5f} | {_percent(metrics['accuracy'])} | "
            f"{_percent(metrics['macro_precision'])} | {_percent(metrics['macro_recall'])} | "
            f"{_percent(metrics['macro_f1'])} |")
    if not found:
        return PENDING.format(source="outputs/evaluation/*/metrics.json",
                              command="python -m src.cli evaluate --part both ...")
    lines += ["", "Rows appear here only once their `metrics.json` exists; nothing is "
                  "carried over by hand."]
    return "\n".join(lines)


SECTIONS: dict[str, Callable[[], str]] = {
    "transfer_study": build_transfer_study,
    "p4_architectures": build_p4_architectures,
    "eval_geometry": build_eval_geometry,
    "final_results": build_final_results,
}


def update(report_path: Path = REPORT, check: bool = False) -> tuple[list[str], list[str]]:
    """Rewrite every AUTO block. Returns (changed, pending) section names."""
    if not report_path.is_file():
        raise FileNotFoundError(f"Report not found: {report_path}")
    text = original = report_path.read_text(encoding="utf-8")
    changed, pending = [], []

    for name, builder in SECTIONS.items():
        pattern = re.compile(
            rf"(<!-- AUTO:{re.escape(name)} -->\n)(.*?)(\n<!-- /AUTO:{re.escape(name)} -->)",
            re.DOTALL)
        if not pattern.search(text):
            raise ValueError(f"Report has no <!-- AUTO:{name} --> block.")
        body = builder()
        if body.lstrip().startswith("> **Not run yet.**"):
            pending.append(name)
        new_text, _ = pattern.subn(lambda m: m.group(1) + body + m.group(3), text)
        if new_text != text:
            changed.append(name)
        text = new_text

    if check:
        if text != original:
            print("Report is STALE. Sections needing regeneration: " + ", ".join(changed))
        return changed, pending

    if text != original:
        report_path.write_text(text, encoding="utf-8")
    return changed, pending


def main() -> None:
    parser = argparse.ArgumentParser(description="Regenerate the measured report sections")
    parser.add_argument("--report", type=Path, default=REPORT)
    parser.add_argument("--check", action="store_true",
                        help="Report staleness without writing; exit 1 if stale.")
    args = parser.parse_args()

    changed, pending = update(args.report, check=args.check)

    if args.check:
        raise SystemExit(1 if changed else 0)

    print(f"Updated {args.report}")
    print(f"  rewritten: {', '.join(changed) if changed else 'nothing changed'}")
    if pending:
        print(f"  still awaiting results: {', '.join(pending)}")
        print("  (those sections carry a visible 'Not run yet' notice, not a fabricated number)")
    else:
        print("  every measured section is backed by an artifact")


if __name__ == "__main__":
    main()
